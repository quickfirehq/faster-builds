VERSION = "1.0"
ISSUES = "https://github.com/quickfirehq/faster-builds/issues"

SCENARIOS = ("no-change", "body", "shared")
LABELS = {
    "no-change": "No-change build",
    "body": "Function-body edit",
    "shared": "Shared-type edit",
}
MARK = "// added by build_baseline.py, removed when it finishes"

# Destination platform for each SDK an app can build for, in order of preference.
PLATFORMS = [
    ("iphonesimulator", "iOS Simulator", "iPhone"),
    ("macosx", "macOS", ""),
    ("xrsimulator", "visionOS Simulator", "Apple Vision"),
    ("appletvsimulator", "tvOS Simulator", "Apple TV"),
    ("watchsimulator", "watchOS Simulator", "Apple Watch"),
]

# Files never edited: dependencies (Pods, packages checked out into DerivedData), build output and tests.
SKIP_PATH = re.compile(
    r"/(DerivedData|\.build|SourcePackages|Pods|Carthage|checkouts|Tests|UITests|[^/]*Tests)/|Tests?\.swift$"
)
# Generated files say so near the top; editing them would be undone by the next generation anyway.
GENERATED = re.compile(r"(?i)auto-?generated|generated by|do not edit")
# A top-level type whose declaration fits on one line ending in "{", e.g. "public final class Theme: Sendable {".
# Protocols are left out: a property added to a protocol would be a requirement, not a change to one type.
TYPE_DECL = re.compile(
    r"^(?:@[\w.]+(?:\([^)]*\))?\s+)*"
    r"((?:(?:public|open|package|internal|fileprivate|private|final|indirect|nonisolated)\s+)*)"
    r"(struct|class|enum|actor)\s+([A-Z]\w*)\b[^{}=]*\{\s*$"
)
# A function whose signature fits on one line ending in "{". Lines with "->" are skipped later: a function with no
# return value can take an extra statement anywhere, while one that returns a value might rely on an implicit return.
FUNC_DECL = re.compile(r"^(\s*)(?:@[\w.]+(?:\([^)]*\))?\s+)*(?:\w+\s+)*func\s+[`\w]+[^{}]*\{\s*$")
# Bodies that other files see (inlinable code) or that a result builder turns into values: an edit there isn't a
# plain function-body edit.
NO_BODY_EDIT_ATTRS = re.compile(r"@(inlinable|_transparent|usableFromInline|_alwaysEmitIntoClient|\w*Builder)\b")
# Build log lines, as xcodebuild prints them. Paths escape spaces with a backslash.
#   SwiftCompile normal arm64 /path/File.swift (in target 'App' from project 'App')
SWIFT_COMPILE = re.compile(r"^SwiftCompile \S+ \S+ (/(?:\\ |[^ ])+\.swift) \(in target")
C_COMPILE = re.compile(r"^CompileC \S+ (/(?:\\ |[^ ])+\.(?:c|m|mm|cc|cpp)) ")
SCRIPT_RAN = re.compile(r"^PhaseScriptExecution ((?:\\ |[^ ])+) /.*\(in target '([^']+)' from project '([^']+)'\)")
EVERY_BUILD = re.compile(
    r"Run script build phase '([^']+)' will be run during every build.*\(in target '([^']+)' from project '([^']+)'\)"
)
#   SwiftCompile (12 tasks) | 3.402 seconds                     (a line of -showBuildTimingSummary)
TIMING_LINE = re.compile(r"^(.+?) \((\d+) tasks?\) \| ([\d.]+) seconds$")
#   /path/File.swift:12:5: warning: instance method 'load()' took 250ms to type-check (limit: 200ms)
SLOW_CHECK = re.compile(r"^(/.*?):(\d+):\d+: warning: (.*) took (\d+)ms to type-check")
ERROR_LINE = re.compile(r"(^|: )(fatal )?error: ")


