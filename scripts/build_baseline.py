def print_report(report):
    say()
    say("Results (median of %d build%s)" % (report["runs"], "" if report["runs"] == 1 else "s"))
    measured = [s for s in SCENARIOS if s in report["scenarios"] and "median_seconds" in report["scenarios"][s]]
    for scenario in SCENARIOS:
        result = report["scenarios"].get(scenario)
        if result is None:
            continue
        if "median_seconds" not in result:
            say("  %-20s skipped: %s" % (LABELS[scenario], result["skipped"]))
            continue
        spread = ""
        if len(result["builds"]) > 1:
            spread = "(%.2f to %.2f)" % (result["min_seconds"], result["max_seconds"])
        files = result["files_compiled_median"]
        say("  %-20s %9s  %-18s %d source file%s compiled" % (
            LABELS[scenario], fmt(result["median_seconds"]), spread, files, "" if files == 1 else "s"))

    if measured:
        kinds = {}
        for scenario in measured:
            for row in report["scenarios"][scenario]["timing_summary"]:
                kinds.setdefault(row["kind"], {})[scenario] = row["seconds"]
        # The biggest kinds in each kind of build, so a no-change build's few small tasks show too.
        top = set()
        for scenario in measured:
            rows = report["scenarios"][scenario]["timing_summary"]
            top |= {row["kind"] for row in sorted(rows, key=lambda r: -r["seconds"])[:5]}
        top = sorted(top, key=lambda k: -max(kinds[k].values()))
        if top:
            say()
            say("Timing summary of the median build, by kind of task (seconds, summed across cores):")
            names = {"no-change": "no change", "body": "body edit", "shared": "shared type"}
            say("  %-34s" % "" + "".join("%12s" % names[s] for s in measured))
            for kind in top:
                cells = "".join("%12s" % ("%.2f" % kinds[kind][s] if s in kinds[kind] else "-") for s in measured)
                say("  %-34s%s" % (kind[:34], cells))
            idle = [names[s] for s in measured if not report["scenarios"][s]["timing_summary"]]
            if idle:
                say("  (%s: no tasks ran; that time went to checking what was already up to date)"
                    % ", ".join(idle))

    scripts = report["every_build_scripts"]
    say()
    if scripts:
        say("Script phases that ran in a no-change build:")
        for entry in scripts:
            why = "  (declares no outputs)" if entry["declares_no_outputs"] else ""
            say("  '%s' in target '%s'%s" % (entry["name"], entry["target"], why))
    elif "no-change" in measured:
        say("No script phase ran in a no-change build.")

    checks = report.get("type_checks")
    if checks:
        say()
        if "error" in checks:
            say("Type-check times: " + checks["error"])
        elif not checks["slow"]:
            say("Nothing took longer than %d ms to type-check (full build: %s)."
                % (checks["limit_ms"], fmt(checks["full_build_seconds"])))
        else:
            say("Slower than %d ms to type-check (slowest first, %d found):" % (checks["limit_ms"], len(checks["slow"])))
            for row in checks["slow"][:20]:
                say("  %6d ms  %s:%d  %s" % (row["ms"], row["file"], row["line"], row["what"]))
            if len(checks["slow"]) > 20:
                say("  ... %d more in %s" % (len(checks["slow"]) - 20, checks["log"]))

    if report["restored"]:
        say()
    for path, status in report["restored"]:
        say("%s: %s" % (path, status))
    for warning in report["warnings"]:
        say("Note: " + warning)
    say()
    say("Logs: " + report["logs"])


