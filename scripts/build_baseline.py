def parse_args(argv):
    extra = []
    if "--" in argv:
        index = argv.index("--")
        argv, extra = argv[:index], argv[index + 1:]
    parser = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0],
        epilog="\n\n".join(__doc__.split("\n\n")[1:]),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        usage="%(prog)s [options] [-- extra xcodebuild arguments]")
    found = parser.add_argument_group("what to build (detected when left out)")
    found.add_argument("--workspace", help="the .xcworkspace to build")
    found.add_argument("--project", help="the .xcodeproj to build")
    found.add_argument("--scheme", help="the scheme (default: the one that builds the app)")
    found.add_argument("--destination", help='an xcodebuild destination, e.g. "platform=iOS Simulator,name=iPhone 17" '
                                             "(default: a Simulator with the newest OS)")
    found.add_argument("--configuration", default="Debug", help="build configuration (default: Debug)")
    found.add_argument("--derived-data", help="build folder (default: the usual DerivedData, so the builds match yours)")
    edits = parser.add_argument_group("the edits (picked automatically when left out)")
    edits.add_argument("--body-file", help="file for the function-body edit")
    edits.add_argument("--shared-file", help="file declaring the type for the shared-type edit")
    edits.add_argument("--shared-type", help="name of the type for the shared-type edit")
    edits.add_argument("--skip", action="append", choices=SCENARIOS, default=[],
                       help="leave out a kind of build (repeat for more)")
    how = parser.add_argument_group("how")
    how.add_argument("--runs", type=int, default=3, help="timed builds of each kind (default 3)")
    how.add_argument("--quick", action="store_true", help="one timed build of each kind (same as --runs 1)")
    how.add_argument("--type-checks", nargs="?", type=int, const=200, metavar="MS",
                     help="also list functions and expressions slower than MS to type-check (default 200); "
                          "a full build into a temporary folder, as long as a clean build")
    how.add_argument("--plan", action="store_true", help="show what would be built and edited, then stop")
    how.add_argument("--json", action="store_true", help="print the results as JSON on stdout; progress goes to stderr")
    how.add_argument("--version", action="version", version="%(prog)s " + VERSION)
    args = parser.parse_args(argv)
    if args.quick:
        args.runs = 1
    if args.runs < 1:
        parser.error("--runs must be at least 1")
    if args.workspace and args.project:
        parser.error("pass --workspace or --project, not both")
    return args, extra


def main(argv):
    global JSON_MODE
    args, extra = parse_args(argv)
    JSON_MODE = args.json
    report = {"tool": "build_baseline.py", "version": VERSION, "ok": False}

    def on_signal(signum, frame):
        raise Interrupted()

    for sig in (signal.SIGTERM, signal.SIGHUP):
        signal.signal(sig, on_signal)

    logs = tempfile.mkdtemp(prefix="build-baseline.")
    report["logs"] = logs
    baseline = None
    try:
        if not shutil.which("xcodebuild"):
            raise Stop("xcodebuild not found: install Xcode and check `xcode-select -p`", 2)
        _, version = run(["xcodebuild", "-version"])
        xcode = {"version": (re.findall(r"^Xcode (\S+)", version, re.M) or ["?"])[0],
                 "build": (re.findall(r"^Build version (\S+)", version, re.M) or ["?"])[0]}
        _, model = run(["sysctl", "-n", "hw.model"])
        report["machine"] = {"model": model.strip(), "cores": os.cpu_count()}
        report["xcode"] = xcode

        container_args, container_name = find_container(args)
        scheme = choose_scheme(container_args, container_name, args)
        scheme_args = container_args + ["-scheme", scheme, "-configuration", args.configuration]
        if args.derived_data:
            scheme_args += ["-derivedDataPath", args.derived_data]
        settings = xcodebuild_json(scheme_args + ["-showBuildSettings", "-json"] + extra)
        destination, destination_label = choose_destination(scheme_args, settings, args)
        base_args = scheme_args + ["-destination", destination] + extra
        settings = xcodebuild_json(base_args + ["-showBuildSettings", "-json"])
        target = app_target(settings) or settings[0]
        build_settings = target["buildSettings"]
        platform_dir = build_settings.get("CONFIGURATION", args.configuration) + \
            build_settings.get("EFFECTIVE_PLATFORM_NAME", "")
        report["settings"] = {
            "container": container_name, "scheme": scheme, "configuration": args.configuration,
            "destination": destination, "destination_name": destination_label,
            "derived_data": args.derived_data or str(Path(build_settings.get("OBJROOT", "")).parent.parent),
            "extra_arguments": extra,
        }
        report["runs"] = args.runs

        say("Project:      %s, scheme %s (%s)" % (container_name, scheme, args.configuration))
        say("Destination:  %s" % destination_label)
        say("Xcode:        %s (%s)" % (xcode.get("version", "?"), xcode.get("build", "?")))
        say("Mac:          %s, %d cores" % (report["machine"]["model"], report["machine"]["cores"]))
        if run(["pgrep", "-x", "Xcode"])[0] == 0:
            report.setdefault("notes", []).append("Xcode was open")
            say("Note:         Xcode is open; its indexing and builds can make these times noisier.")

        baseline = Baseline(args, base_args, logs)
        wanted = [s for s in SCENARIOS if s not in args.skip]
        git = Git()
        for path, status in git.leftovers(fix=not args.plan):
            baseline.warnings.append("%s: %s" % (rel(path), status))
            say("Note:         %s: %s" % (rel(path), status))
        objroot = build_settings.get("OBJROOT", "")
        for kind, path in (("body", args.body_file), ("shared", args.shared_file)):
            if path and kind in wanted:
                if not os.path.isfile(path):
                    raise Stop("--%s-file %s: no such file" % (kind, path), 2)
                reason = git.why_not_editable(os.path.realpath(path))
                if reason:
                    raise Stop("--%s-file %s: %s, so it won't be edited" % (kind, path, reason), 2)

        if not args.plan:
            say()
            say("Warm-up build (not timed; a full build if nothing is built yet)...")
            seconds, _ = baseline.must_build("warm-up")
            say("  %s" % fmt(seconds))

        compiled = compiled_sources(objroot, platform_dir)
        sources = candidate_sources(compiled, git, git.root or HERE) if ("body" in wanted or "shared" in wanted) else []
        counts = references(sources)
        plan = {}
        if "shared" in wanted:
            if args.shared_file:
                plan["shared"], ok = override_edit("shared", args.shared_file, git, sources, counts,
                                                   args.shared_type, compiled)
                if not ok:
                    baseline.warnings.append("%s isn't in the last build's file lists" % args.shared_file)
            else:
                plan["shared"] = shared_edits(sources, counts, args.shared_type)
                if plan["shared"] and plan["shared"][0].users < 3:
                    baseline.warnings.append(
                        "the most used type in a clean file, %s, is used in only %d other file(s); pass "
                        "--shared-file for a type many files use" % (plan["shared"][0].name, plan["shared"][0].users))
        if "body" in wanted:
            avoid = plan["shared"][0].source.path if plan.get("shared") else None
            if args.body_file:
                plan["body"], ok = override_edit("body", args.body_file, git, sources, counts, None, compiled)
                if not ok:
                    baseline.warnings.append("%s isn't in the last build's file lists" % args.body_file)
            else:
                plan["body"] = body_edits(sources, counts, avoid)
        if ("body" in wanted or "shared" in wanted) and not git.root:
            baseline.warnings.append("not a git repository, so no file was edited: the edit builds were skipped")

        report["edits"] = {s: {"file": rel(e[0].source.path), "where": e[0].where} for s, e in plan.items() if e}
        if args.plan:
            say()
            say("Would build: xcodebuild build " + " ".join(base_args))
            if not compiled:
                say("No file lists from an earlier build, so the edit files can't be picked yet.")
            for scenario in ("body", "shared"):
                if scenario in plan:
                    edit = (plan[scenario] or [None])[0]
                    say("%-20s %s" % (LABELS[scenario] + ":", "%s (%s)" % (rel(edit.source.path), edit.where)
                                      if edit else "no file found"))
            report["ok"] = True
            report["plan"] = True
            return report

        last = wanted[-1] if wanted else None
        for scenario in wanted:
            baseline.measure(scenario, plan.get(scenario), last=(scenario == last))
        baseline.restorer.restore_all()

        report["scenarios"] = baseline.results
        no_change = baseline.results.get("no-change", {})
        warned = set()
        for name in os.listdir(logs):
            if name.endswith(".log"):
                with open(os.path.join(logs, name), errors="replace") as f:
                    warned |= every_build_warnings(f.read())
        report["every_build_scripts"] = [
            dict(entry, declares_no_outputs=(entry["name"], entry["target"], entry["project"]) in warned)
            for entry in no_change.get("scripts_ran", [])]

        if args.type_checks is not None:
            report["type_checks"] = baseline.type_checks(args.type_checks)

        report["ok"] = any("median_seconds" in r for r in baseline.results.values())
        return report
    except Stop as stop:
        report["error"] = str(stop)
        report["exit_code"] = stop.code
        return report
    except (KeyboardInterrupt, Interrupted):
        report["error"] = "stopped before it finished"
        report["exit_code"] = 130
        return report
    except Exception as error:
        # Something this script didn't expect. Keep the details for a bug report; the files are still restored below.
        details = os.path.join(logs, "error.txt")
        with open(details, "w") as f:
            f.write(traceback.format_exc())
        report["error"] = "unexpected error (%s: %s). Details: %s. Please report it at %s" % (
            type(error).__name__, error, details, ISSUES)
        report["exit_code"] = 1
        return report
    finally:
        if baseline:
            try:
                baseline.restorer.restore_all()
            except Exception as error:
                report["error"] = "couldn't restore an edited file (%s); the originals are in %s" % (error, logs)
                report["exit_code"] = 1
            report["restored"] = []
            for path, status in baseline.restorer.report:
                clean = Git().is_clean(path) if status == "restored" else None
                if clean is False:
                    status += ", but git still shows changes"
                elif clean:
                    status += " (git shows no changes)"
                report["restored"].append((rel(path), status))
            report["warnings"] = baseline.warnings
        else:
            report.setdefault("restored", [])
            report.setdefault("warnings", [])


if __name__ == "__main__":
    result = main(sys.argv[1:])
    if JSON_MODE:
        result["restored"] = [{"file": f, "status": s} for f, s in result.get("restored", [])]
        print(json.dumps(result, indent=2))
    elif "error" in result:
        for path, status in result.get("restored", []):
            say("%s: %s" % (path, status))
        print("build_baseline.py: " + result["error"], file=sys.stderr)
        if result.get("logs"):
            print("Logs: " + result["logs"], file=sys.stderr)
    elif not result.get("plan"):
        print_report(result)
    sys.exit(result.get("exit_code", 0 if result.get("ok") else 1))
