#!/usr/bin/env python3
"""Measures a build baseline for an Xcode project in one run.

It finds the workspace or project, the app's scheme and a Simulator, then times three standard builds, each
several times, and keeps the median:

  no-change     a build with nothing changed: what the build system costs before any real work
  body          a one-line change inside a function body: the most common edit
  shared        a new property on a type that many files use: how far a change can spread

It also prints the timing summary of each kind of build and the script phases that run on every build, and,
with --type-checks, the functions and expressions slowest to type-check.

It changes your source files only to make the two edits, only files that git tracks and that have no
uncommitted changes, and it always puts them back: when it finishes, fails or is stopped with Ctrl-C. If it is
killed outright (kill -9, or a coding agent's time limit), the next run puts them back before it starts.
Python 3.9 or later, standard library only.

Examples:
  build_baseline.py                                   # everything detected, 3 builds of each kind
  build_baseline.py --quick                           # 1 build of each kind
  build_baseline.py --plan                            # show what it would build and edit, build nothing
  build_baseline.py --scheme MyApp --body-file Sources/Feature/ProfileView.swift --type-checks
  build_baseline.py --json > baseline.json            # for scripts and coding agents; progress goes to stderr
  build_baseline.py -- -skipPackagePluginValidation   # extra xcodebuild arguments after --
"""

