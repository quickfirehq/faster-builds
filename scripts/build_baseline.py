# --- running xcodebuild -------------------------------------------------------------------------------------

def run(cmd, log=None, stdout_only=False):
    """Runs a command; returns (exit code, output). Output goes to the log file when one is given.
    With stdout_only, standard error is kept apart and returned only when the command fails."""
    out = open(log, "w") if log else subprocess.PIPE
    err = subprocess.PIPE if stdout_only else subprocess.STDOUT
    proc = subprocess.Popen(cmd, stdout=out, stderr=err, text=True)
    try:
        stdout, stderr = proc.communicate()
        if stdout_only and proc.returncode != 0:
            stdout = (stdout or "") + (stderr or "")
    except BaseException:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
        raise
    finally:
        if log:
            out.close()
    if log:
        with open(log, errors="replace") as f:
            stdout = f.read()
    return proc.returncode, stdout


def first_errors(text, limit=10):
    lines = [l for l in text.splitlines() if ERROR_LINE.search(l)]
    return lines[:limit] or text.splitlines()[-20:]


def xcodebuild_json(args):
    code, out = run(["xcodebuild"] + args, stdout_only=True)
    if code != 0:
        raise Stop("xcodebuild %s failed:\n  %s" % (" ".join(args), "\n  ".join(first_errors(out))), 2)
    starts = [i for i in (out.find("["), out.find("{")) if i >= 0]
    try:
        if not starts:
            raise ValueError
        start = min(starts)
        return json.loads(out[start:])
    except ValueError:
        raise Stop("couldn't read the output of xcodebuild %s" % " ".join(args), 2)


# --- detecting the project, scheme and destination ----------------------------------------------------------

def find_container(args):
    if args.workspace:
        return ["-workspace", args.workspace], args.workspace
    if args.project:
        return ["-project", args.project], args.project
    here = Path.cwd()
    workspaces = sorted(p.name for p in here.glob("*.xcworkspace"))
    projects = sorted(p.name for p in here.glob("*.xcodeproj"))
    if len(workspaces) == 1:
        return ["-workspace", workspaces[0]], workspaces[0]
    if len(workspaces) > 1:
        raise Stop("more than one workspace here (%s): pass --workspace" % ", ".join(workspaces), 2)
    if len(projects) == 1:
        return ["-project", projects[0]], projects[0]
    if len(projects) > 1:
        raise Stop("more than one project here (%s): pass --project" % ", ".join(projects), 2)
    if (here / "Package.swift").exists():
        return [], "Package.swift"
    raise Stop("no .xcworkspace, .xcodeproj or Package.swift in %s: run this from your project's folder, "
               "or pass --workspace or --project" % here, 2)


def app_target(settings):
    """The settings of the first app target in -showBuildSettings -json output, or None."""
    for entry in settings:
        if entry["buildSettings"].get("PRODUCT_TYPE", "").startswith("com.apple.product-type.application"):
            return entry
    return None


def choose_scheme(container_args, container_name, args):
    if args.scheme:
        return args.scheme
    listing = xcodebuild_json(container_args + ["-list", "-json"])
    info = listing.get("workspace") or listing.get("project") or {}
    schemes = info.get("schemes", [])
    if not schemes:
        raise Stop("no schemes found: pass --scheme", 2)
    if len(schemes) == 1:
        return schemes[0]
    noise = re.compile(r"(?i)(tests?$|uitests|^pods-|generate project|-workspace$)")
    stem = Path(container_name).stem
    candidates = [s for s in schemes if not noise.search(s)] or schemes
    candidates.sort(key=lambda s: (s != stem, s.lower() != stem.lower(), not s.startswith(stem)))
    for scheme in candidates[:10]:
        code, out = run(["xcodebuild"] + container_args + ["-scheme", scheme, "-showBuildSettings", "-json"],
                        stdout_only=True)
        if code == 0:
            try:
                settings = json.loads(out[out.find("["):])
            except ValueError:
                continue
            if app_target(settings):
                return scheme
    raise Stop("couldn't tell which scheme builds the app; pass --scheme (one of: %s)" % ", ".join(schemes), 2)


def parse_destinations(text):
    found = []
    for block in re.findall(r"\{ (.*?) \}", text):
        fields = dict(re.findall(r"(\w+):(.*?)(?=, \w+:|$)", block))
        found.append(fields)
    return found


def version_key(text):
    return tuple(int(x) for x in re.findall(r"\d+", text or "0"))


def choose_destination(base_args, settings, args):
    if args.destination:
        return args.destination, args.destination
    target = app_target(settings) or (settings[0] if settings else None)
    supported = (target["buildSettings"].get("SUPPORTED_PLATFORMS", "") if target else "").split()
    code, out = run(["xcodebuild"] + base_args + ["-showdestinations"])
    if code != 0:
        raise Stop("xcodebuild -showdestinations failed: pass --destination\n  %s"
                   % "\n  ".join(first_errors(out)), 2)
    destinations = [d for d in parse_destinations(out)
                    if "placeholder" not in d.get("id", "") and "variant" not in d]
    for sdk, platform, family in PLATFORMS:
        if sdk not in supported:
            continue
        matches = [d for d in destinations if d.get("platform") == platform]
        if not matches:
            continue
        # Newest OS first, then the standard device names (a renamed or custom device sorts last).
        matches.sort(key=lambda d: (not d.get("name", "").startswith(family), [-v for v in version_key(d.get("OS"))]))
        best = matches[0]
        label = best.get("name", best["id"])
        if best.get("OS"):
            label += " (%s %s)" % (platform, best["OS"])
        return "id=" + best["id"], label
    raise Stop("no Simulator or Mac destination found for platforms %s: pass --destination"
               % (" ".join(supported) or "unknown"), 2)


# --- git ----------------------------------------------------------------------------------------------------

class Git:
    def __init__(self):
        code, out = run(["git", "rev-parse", "--show-toplevel"])
        self.root = Path(os.path.realpath(out.strip())) if code == 0 else None
        self.tracked = set()
        self.dirty = set()
        if self.root:
            self.refresh()

    def refresh(self):
        _, out = run(["git", "-C", str(self.root), "ls-files", "-z"])
        self.tracked = {os.path.realpath(self.root / p) for p in out.split("\0") if p}
        _, out = run(["git", "-C", str(self.root), "status", "--porcelain", "-z", "--untracked-files=no"])
        dirty = set()
        entries = out.split("\0")
        i = 0
        while i < len(entries):
            entry = entries[i]
            if len(entry) > 3:
                dirty.add(os.path.realpath(self.root / entry[3:]))
                if entry[0] in "RC":
                    i += 1
            i += 1
        self.dirty = dirty

    def why_not_editable(self, path):
        if not self.root:
            return "not in a git repository (edits need git, to prove a file is clean before changing it)"
        if path not in self.tracked:
            return "not tracked by git"
        if path in self.dirty:
            return "has uncommitted changes"
        return None

    def is_clean(self, path):
        self.refresh()
        return path in self.tracked and path not in self.dirty

    def leftovers(self, fix):
        """Files an earlier run left edited because it was killed before it could restore them (kill -9, or a
        coding agent's time limit). When the marked line is a file's only change, `fix` removes it."""
        if not self.root:
            return []
        _, out = run(["git", "-C", str(self.root), "grep", "-l", "-F", "-e", MARK, "--", "*.swift"])
        found = []
        for name in out.splitlines():
            path = os.path.realpath(self.root / name)
            _, diff = run(["git", "-C", str(self.root), "diff", "-U0", "--", name])
            changed = [l for l in diff.splitlines()
                       if l[:1] in "+-" and not l.startswith("+++") and not l.startswith("---")]
            only_ours = bool(changed) and all(l.startswith("+") and MARK in l for l in changed)
            if only_ours and fix:
                text = Path(path).read_text()
                Path(path).write_text("".join(l for l in text.splitlines(keepends=True) if MARK not in l))
                found.append((path, "put back: an earlier run was stopped before it could restore it"))
            elif only_ours:
                found.append((path, "left edited by an earlier run that was stopped; the next run puts it back"))
            else:
                found.append((path, "has a line added by an earlier run, plus other changes: delete the line "
                                    "ending in \"%s\" by hand (git checkout would drop your changes too)" % MARK))
        if found:
            self.refresh()
        return found


# --- picking the files to edit ------------------------------------------------------------------------------

class Source:
    """A Swift file, with the places in it where an edit can go."""

    def __init__(self, path):
        self.path = path
        self.text = Path(path).read_text(errors="replace")
        self.lines = self.text.splitlines(keepends=True)
        self.words = set(re.findall(r"\b[A-Z]\w*\b", self.text))
        self.types = []  # (line index, name, access, kind)
        self.funcs = []  # (line index, indent)
        self.scan()

    def scan(self):
        """Finds top-level types and functions, skipping comments and multi-line strings. A light scan, not a
        parser: whatever it gets wrong, the build after the edit shows (a failed build moves on to another file)."""
        in_comment = in_string = False
        if_depth = 0
        for i, line in enumerate(self.lines):
            stripped = line.strip()
            if in_comment:
                if "*/" in line:
                    in_comment = False
                continue
            if line.count('"""') % 2 == 1:
                in_string = not in_string
                continue
            if in_string:
                continue
            if stripped.startswith("/*") and "*/" not in stripped:
                in_comment = True
                continue
            if stripped.startswith("//"):
                continue
            if stripped.startswith("#if"):
                if_depth += 1
            elif stripped.startswith("#endif"):
                if_depth = max(0, if_depth - 1)
            match = TYPE_DECL.match(line)
            if match and if_depth == 0:
                modifiers = match.group(1).split()
                access = next((m for m in ("public", "open", "package") if m in modifiers), "")
                self.types.append((i, match.group(3), "public" if access == "open" else access, match.group(2)))
            match = FUNC_DECL.match(line)
            if match and "->" not in line and line.count("(") == line.count(")"):
                attributes = "".join(self.lines[max(0, i - 3):i + 1])
                if not NO_BODY_EDIT_ATTRS.search(attributes):
                    self.funcs.append((i, match.group(1)))

    def indent_after(self, index, fallback):
        """The indentation of the first line inside the block that opens on line `index`."""
        for line in self.lines[index + 1:]:
            if line.strip():
                found = re.match(r"\s*", line).group(0)
                return found if len(found) > len(fallback) else fallback + "    "
        return fallback + "    "

    def with_line(self, index, new_line):
        return "".join(self.lines[:index + 1]) + new_line + "\n" + "".join(self.lines[index + 1:])


def compiled_sources(objroot, platform_dir):
    """Swift files the last build compiled, from the build folder's per-target file lists."""
    files = set()
    root = Path(objroot)
    if not root.is_dir():
        return files
    for file_list in root.rglob("*.SwiftFileList"):
        if "/%s/" % platform_dir not in str(file_list):
            continue
        for line in file_list.read_text(errors="replace").splitlines():
            line = line.strip().strip('"').replace("\\ ", " ")
            if line.endswith(".swift"):
                files.add(os.path.realpath(line))
    return files


def candidate_sources(compiled, git, here):
    """The compiled files that may be edited: inside this repository, clean in git, not tests or generated."""
    sources = []
    for path in sorted(compiled):
        if not path.startswith(str(here) + os.sep) or SKIP_PATH.search(path) or not os.path.isfile(path):
            continue
        if git.why_not_editable(path):
            continue
        try:
            source = Source(path)
        except OSError:
            continue
        if GENERATED.search(source.text[:600]):
            continue
        sources.append(source)
    return sources


def references(sources):
    """For each type name declared once, how many other files mention it."""
    declared = {}
    for source in sources:
        for entry in source.types:
            declared.setdefault(entry[1], []).append(source)
    counts = {}
    for name, owners in declared.items():
        if len(owners) == 1:
            counts[name] = sum(1 for s in sources if s is not owners[0] and name in s.words)
    return counts


def shared_edits(sources, counts, wanted_type=None):
    """Edit candidates for the shared-type build, most widely used type first."""
    options = []
    for source in sources:
        for index, name, access, kind in source.types:
            if wanted_type and name != wanted_type:
                continue
            if name in counts or wanted_type:
                options.append((counts.get(name, 0), source, index, name, access, kind))
    options.sort(key=lambda o: (-o[0], len(o[1].lines), o[1].path))
    return [SharedEdit(*o) for o in options]


def body_edits(sources, counts, avoid=None):
    """Edit candidates for the function-body build: files few others depend on, of typical size, first."""
    with_funcs = [s for s in sources if s.funcs and s.path != avoid]
    if not with_funcs:
        return []
    median_size = statistics.median(len(s.lines) for s in with_funcs)

    def leafness(source):
        return sum(counts.get(entry[1], 0) for entry in source.types)

    with_funcs.sort(key=lambda s: (leafness(s), abs(len(s.lines) - median_size), s.path))
    edits = []
    for source in with_funcs:
        index, indent = source.funcs[len(source.funcs) // 2]
        edits.append(BodyEdit(source, index, indent))
    return edits


class BodyEdit:
    def __init__(self, source, index, indent):
        self.source, self.index, self.indent = source, index, indent
        name = re.search(r"func\s+([`\w]+)", source.lines[index]).group(1)
        self.where = "in func %s, line %d" % (name, index + 1)

    def content(self, n):
        line = "%slet _ = %d  %s" % (self.source.indent_after(self.index, self.indent), 1000 + n, MARK)
        return self.source.with_line(self.index, line)


class SharedEdit:
    def __init__(self, users, source, index, name, access, kind):
        self.users, self.source, self.index, self.name, self.access, self.kind = users, source, index, name, access, kind
        self.where = "%s %s, used in %d other file%s" % (kind, name, users, "" if users == 1 else "s")

    def content(self, n):
        # A new member name each time changes the type's interface, so files that use the type rebuild too.
        indent = self.source.indent_after(self.index, "")
        access = self.access + " " if self.access else ""
        line = "%s%svar buildBaselineMarker%d: Int { %d }  %s" % (indent, access, 1000 + n, n, MARK)
        return self.source.with_line(self.index, line)


def override_edit(kind, path, git, sources, counts, wanted_type, compiled):
    real = os.path.realpath(path)
    if not os.path.isfile(real):
        raise Stop("--%s-file %s: no such file" % (kind, path), 2)
    reason = git.why_not_editable(real)
    if reason:
        raise Stop("--%s-file %s: %s, so it won't be edited" % (kind, path, reason), 2)
    source = next((s for s in sources if s.path == real), None) or Source(real)
    if kind == "body":
        if not source.funcs:
            raise Stop("--body-file %s: no function without a return value to add a line to" % path, 2)
        return [BodyEdit(source, *source.funcs[len(source.funcs) // 2])], real in compiled
    found = shared_edits([source], counts, wanted_type)
    if not found:
        raise Stop("--shared-file %s: no top-level struct, class, enum or actor%s to add a property to"
                   % (path, " named " + wanted_type if wanted_type else ""), 2)
    return found, real in compiled


# --- restoring edited files ---------------------------------------------------------------------------------

class Restorer:
    """Keeps each edited file's original bytes and puts them back, whatever happens."""

    def __init__(self, backup_dir):
        self.backup_dir = backup_dir
        self.files = {}  # path -> [original bytes, original stat, last bytes written]
        self.report = []
        self.backups = 0

    def write(self, path, text):
        if path not in self.files:
            original = Path(path).read_bytes()
            stat = os.stat(path)
            self.backups += 1
            backup = Path(self.backup_dir) / ("original-%d-%s" % (self.backups, Path(path).name))
            backup.write_bytes(original)
            self.files[path] = [original, stat, original]
        expected = self.files[path][2]
        if Path(path).read_bytes() != expected:
            raise Stop("%s changed while the script was running; stopping without touching it again" % path)
        data = text.encode()
        Path(path).write_bytes(data)
        self.files[path][2] = data

    def restore(self, path):
        if path not in self.files:
            return
        original, stat, written = self.files.pop(path)
        current = Path(path).read_bytes() if os.path.exists(path) else None
        if current == original:
            self.report.append((path, "unchanged"))
        elif current == written:
            Path(path).write_bytes(original)
            os.utime(path, ns=(stat.st_atime_ns, stat.st_mtime_ns))
            self.report.append((path, "restored"))
        else:
            self.report.append((path, "changed by something else during the run: left as it is; the original is "
                                      "in %s" % self.backup_dir))

    def restore_all(self):
        for path in list(self.files):
            self.restore(path)


# --- parsing build logs -------------------------------------------------------------------------------------

def compiled_in_log(text):
    files = set()
    for line in text.splitlines():
        match = SWIFT_COMPILE.match(line) or C_COMPILE.match(line)
        if match:
            files.add(os.path.realpath(match.group(1).replace("\\ ", " ")))
    return files


def timing_summary(text):
    rows = []
    inside = False
    for line in text.splitlines():
        if line.startswith("Build Timing Summary"):
            inside, rows = True, []
        elif line.startswith("** BUILD"):
            inside = False
        elif inside:
            match = TIMING_LINE.match(line.strip())
            if match:
                rows.append({"kind": match.group(1), "tasks": int(match.group(2)), "seconds": float(match.group(3))})
    return rows


def scripts_in_log(text):
    ran = []
    for line in text.splitlines():
        match = SCRIPT_RAN.match(line)
        if match:
            entry = {"name": match.group(1).replace("\\ ", " "), "target": match.group(2),
                     "project": match.group(3)}
            if entry not in ran:
                ran.append(entry)
    return ran


def every_build_warnings(text):
    return {(m.group(1), m.group(2), m.group(3)) for m in EVERY_BUILD.finditer(text)}


# --- the measurement ----------------------------------------------------------------------------------------

class Baseline:
    def __init__(self, args, base_args, logs):
        self.args, self.base_args, self.logs = args, base_args, logs
        self.restorer = Restorer(logs)
        self.warnings = []
        self.results = {}

    def build(self, name, extra=()):
        log = os.path.join(self.logs, name + ".log")
        start = time.monotonic()
        code, out = run(["xcodebuild", "build"] + self.base_args + list(extra), log=log)
        return code, time.monotonic() - start, out, log

    def must_build(self, name, extra=()):
        code, seconds, out, log = self.build(name, extra)
        if code != 0:
            raise Stop("the %s build failed. First errors (full log: %s):\n  %s"
                       % (name, log, "\n  ".join(first_errors(out))))
        return seconds, out

    def timed_builds(self, scenario, edit=None):
        builds = []
        for i in range(1, self.args.runs + 1):
            if edit:
                self.restorer.write(edit.source.path, edit.content(i))
            code, seconds, out, log = self.build("%s-%d" % (scenario, i), ["-showBuildTimingSummary"])
            if code != 0:
                return builds, "the build failed after the edit (log: %s):\n  %s" % (
                    log, "\n  ".join(first_errors(out, 5)))
            compiled = compiled_in_log(out)
            if edit and edit.source.path not in compiled:
                return builds, "the build didn't compile %s, so it isn't part of this scheme" % edit.source.path
            builds.append({"seconds": round(seconds, 3), "files_compiled": len(compiled), "log": log,
                           "summary": timing_summary(out), "scripts_ran": scripts_in_log(out)})
            say("  build %d of %d: %s  (%d source file%s compiled)" % (
                i, self.args.runs, fmt(seconds), len(compiled), "" if len(compiled) == 1 else "s"))
        return builds, None

    def measure(self, scenario, edits=None, last=False):
        say()
        if scenario == "no-change":
            say("%s, %d time%s:" % (LABELS[scenario], self.args.runs, "" if self.args.runs == 1 else "s"))
            builds, error = self.timed_builds(scenario)
            if error:
                raise Stop(error)
            self.results[scenario] = summarize(builds)
            return
        if not edits:
            self.results[scenario] = {"skipped": "no file to edit was found (see --%s-file)" % scenario}
            say("%s: skipped, no file to edit was found (pass --%s-file)" % (LABELS[scenario], scenario))
            return
        failures = []
        attempts = edits[:3]
        for number, edit in enumerate(attempts, 1):
            say("%s: %s (%s), %d time%s:" % (LABELS[scenario], rel(edit.source.path), edit.where,
                                             self.args.runs, "" if self.args.runs == 1 else "s"))
            try:
                builds, error = self.timed_builds(scenario, edit)
            finally:
                self.restorer.restore(edit.source.path)
            if not error or builds:
                result = summarize(builds)
                result.update({"file": rel(edit.source.path), "where": edit.where})
                if error:
                    result["note"] = error
                if scenario == "shared" and edit.users >= 2 and result["files_compiled_median"] <= 1:
                    self.warnings.append("the shared-type edit compiled only %d file: %s may not be used as "
                                         "widely as it looked" % (result["files_compiled_median"], edit.name))
                self.results[scenario] = result
                break
            say("  " + error)
            failures.append({"file": rel(edit.source.path), "error": error})
            if number < len(attempts):
                self.settle("%s-retry-%d" % (scenario, number))
                say("  trying the next file instead")
        else:
            self.results[scenario] = {"skipped": "the edits didn't build", "attempts": failures}
        if failures and "skipped" not in self.results[scenario]:
            self.results[scenario]["attempts"] = failures
        if not last:
            self.settle(scenario)

    def settle(self, scenario):
        """An untimed build after a file is restored, so the next measurement starts from a finished build."""
        say("  rebuilding with the file restored (not timed)...")
        self.must_build("%s-restored" % scenario)

    def type_checks(self, limit):
        say()
        say("Type-check times: a full build into a temporary folder, with warnings over %d ms..." % limit)
        derived = tempfile.mkdtemp(prefix="type-checks.", dir=self.logs)
        flags = ("$(inherited) -Xfrontend -warn-long-function-bodies=%d "
                 "-Xfrontend -warn-long-expression-type-checking=%d" % (limit, limit))
        args = [a for a in self.base_args]
        if "-derivedDataPath" in args:
            index = args.index("-derivedDataPath")
            del args[index:index + 2]
        log = os.path.join(self.logs, "type-checks.log")
        try:
            start = time.monotonic()
            code, out = run(["xcodebuild", "build", "-derivedDataPath", derived] + args +
                            ["OTHER_SWIFT_FLAGS=" + flags], log=log)
            seconds = time.monotonic() - start
        finally:
            shutil.rmtree(derived, ignore_errors=True)
        if code != 0:
            return {"error": "the build failed (log: %s)" % log, "log": log}
        found = {}
        for line in out.splitlines():
            match = SLOW_CHECK.match(line)
            if match:
                key = (match.group(1), int(match.group(2)), match.group(3))
                found[key] = max(found.get(key, 0), int(match.group(4)))
        rows = [{"ms": ms, "file": rel(os.path.realpath(path)), "line": line, "what": what}
                for (path, line, what), ms in found.items()]
        rows.sort(key=lambda r: -r["ms"])
        return {"limit_ms": limit, "full_build_seconds": round(seconds, 2), "slow": rows, "log": log}


def summarize(builds):
    times = [b["seconds"] for b in builds]
    middle = sorted(builds, key=lambda b: b["seconds"])[(len(builds) - 1) // 2]
    return {
        "median_seconds": round(statistics.median(times), 3),
        "min_seconds": min(times),
        "max_seconds": max(times),
        "files_compiled_median": int(statistics.median(b["files_compiled"] for b in builds)),
        "builds": [{k: b[k] for k in ("seconds", "files_compiled", "log")} for b in builds],
        "timing_summary": middle["summary"],
        "scripts_ran": middle["scripts_ran"],
    }


HERE = Path(os.path.realpath(os.getcwd()))


def rel(path):
    try:
        return str(Path(path).relative_to(HERE))
    except ValueError:
        return str(path)


